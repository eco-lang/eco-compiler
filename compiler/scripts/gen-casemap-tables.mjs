#!/usr/bin/env node
// Generates runtime/src/allocator/CaseMapTables.hpp, the Unicode case-mapping tables behind
// Char.toUpper/toLower and String.toUpper/toLower (plans/char-case-mapping-elm-exact.md):
//
//     node compiler/scripts/gen-casemap-tables.mjs > runtime/src/allocator/CaseMapTables.hpp
//     node compiler/scripts/gen-casemap-tables.mjs --check runtime/src/allocator/CaseMapTables.hpp
//
// The tables are the running node's own String.prototype.toUpperCase/toLowerCase, which is what
// Elm on node does (`_Utils_chr(char.toUpperCase())`), so the reference is node's Unicode
// version. Every fact the Char encoding (KERN_008) relies on is asserted here, on every run.
// `--check` exits 1 when the running node's Unicode version differs from the file's, or when the
// regenerated bytes differ (apart from the informational node/ICU lines).
import fs from 'node:fs';

const MAX_UNITS = 3;          // CharValue::kMaxCharUnits with expansions
const MAX_ENTRIES = 255;      // 8-bit rank field (bits 21-28)
const RANK_SHIFT = 21;
const RESERVED_LIMIT = 0x20000000;   // bits 29-31 must be clear

function fail(msg) {
    process.stderr.write('gen-casemap-tables: ' + msg + '\n');
    process.exit(1);
}
function assert(cond, msg) { if (!cond) fail('assertion failed: ' + msg); }

const isSurrogate = (c) => c >= 0xD800 && c <= 0xDFFF;
const cpsOf = (s) => Array.from(s, (ch) => ch.codePointAt(0));
const hex = (v, w = 4) => '0x' + v.toString(16).toUpperCase().padStart(w, '0');
const cmpSeq = (a, b) => {
    for (let i = 0; i < Math.min(a.length, b.length); i++) if (a[i] !== b[i]) return a[i] - b[i];
    return a.length - b.length;
};

function generate() {
    // 1. Per-code-point mappings; multi-code-point results go into E.
    const E = new Set();
    const up = new Map(), lo = new Map();   // c -> result string, only when it differs
    for (let c = 0; c <= 0x10FFFF; c++) {
        if (isSurrogate(c)) continue;
        const s = String.fromCodePoint(c);
        const U = s.toUpperCase(), L = s.toLowerCase();
        if (U !== s) up.set(c, U);
        if (L !== s) lo.set(c, L);
        if (cpsOf(U).length > 1) E.add(U);
        if (cpsOf(L).length > 1) E.add(L);
    }
    // 2. Closure under toUpperCase/toLowerCase.
    const work = [...E];
    while (work.length) {
        const e = work.pop();
        for (const f of [(x) => x.toUpperCase(), (x) => x.toLowerCase()]) {
            const t = f(e);
            const concat = cpsOf(e).map((c) => f(String.fromCodePoint(c))).join('');
            assert(t === concat, 'context-free mapping of closure string ' + JSON.stringify(e));
            if (cpsOf(t).length > 1 && !E.has(t)) { E.add(t); work.push(t); }
        }
    }
    // 3. Facts the encoding needs.
    for (const e of E) {
        const cps = cpsOf(e);
        assert(cps.every((c) => c < 0xD800), 'expansion code points below U+D800: ' + JSON.stringify(e));
        assert(cps.length >= 2 && cps.length <= MAX_UNITS,
            'expansion of ' + cps.length + ' code points ' + JSON.stringify(e) +
            ' (raise kMaxExpansionUnits, CharValue::kMaxCharUnits and every buffer sized by it)');
        assert(!cps.includes(0x3A3), 'no expansion contains U+03A3');
    }
    assert(E.size <= MAX_ENTRIES, E.size + ' expansions exceed the 8-bit rank field (255)');
    assert('Σ'.toLowerCase() === 'σ', "'Σ'.toLowerCase() is σ");
    // 4. Rank order: code-point sequence, a proper prefix first; JS `<` must agree.
    const entries = [...E].map((e) => ({ str: e, cps: cpsOf(e) })).sort((a, b) => cmpSeq(a.cps, b.cps));
    for (let i = 1; i < entries.length; i++) {
        assert(entries[i - 1].str < entries[i].str, 'JS string order agrees with rank order');
    }
    const rankOf = new Map(entries.map((e, i) => [e.str, i]));
    // 5. Char values.
    const value = (str) => {
        const cps = cpsOf(str);
        if (cps.length === 1) return cps[0];
        const v = (cps[0] | ((rankOf.get(str) + 1) << RANK_SHIFT)) >>> 0;
        assert(v < RESERVED_LIMIT, 'bits 29-31 clear in ' + hex(v, 8));
        return v;
    };
    // 6. Tables.
    const pairs = (m) => [...m.entries()].filter(([c]) => c >= 0x80).map(([c, r]) => [c, value(r)]);
    const kUpper = pairs(up), kLower = pairs(lo);
    const kEntries = entries.map((e) => ({
        cps: e.cps, upper: value(e.str.toUpperCase()), lower: value(e.str.toLowerCase()),
    }));
    // 7. Final_Sigma classes.
    const rangesOf = (re) => {
        const out = [];
        let start = -1;
        for (let c = 0; c <= 0x110000; c++) {
            const ok = c <= 0x10FFFF && !isSurrogate(c) && re.test(String.fromCodePoint(c));
            if (ok && start < 0) start = c;
            if (!ok && start >= 0) { out.push([start, c - 1]); start = -1; }
        }
        return out;
    };
    const kCased = rangesOf(/^\p{Cased}$/u);
    const kCaseIgnorable = rangesOf(/^\p{Case_Ignorable}$/u);
    const inRanges = (rs, c) => {
        let a = 0, b = rs.length - 1;
        while (a <= b) {
            const m = (a + b) >> 1;
            if (c < rs[m][0]) b = m - 1; else if (c > rs[m][1]) a = m + 1; else return true;
        }
        return false;
    };
    const cased = (c) => inRanges(kCased, c), ignorable = (c) => inRanges(kCaseIgnorable, c);
    // 8. Final_Sigma self-test: the greedy rule against node on context strings.
    const finalSigma = (cps, i) => {
        let j = i - 1;
        while (j >= 0 && ignorable(cps[j])) j--;
        const before = j >= 0 && cased(cps[j]);
        let k = i + 1;
        while (k < cps.length && ignorable(cps[k])) k++;
        const after = k < cps.length && cased(cps[k]);
        return before && !after;
    };
    const lowerByRule = (s) => {
        const cps = cpsOf(s);
        return cps.map((c, i) => c === 0x3A3 ? (finalSigma(cps, i) ? 'ς' : 'σ')
            : String.fromCodePoint(c).toLowerCase()).join('');
    };
    const S = 'Σ';
    const xs = new Set([0x20, 0x31, 0x2E]);
    for (const [a, b] of [...kCased, ...kCaseIgnorable]) { xs.add(a); xs.add(b); }
    const ys = ['A', 'α', ' ', "'", '.', '́'];
    let sigmaChecks = 0;
    const checkSigma = (s) => {
        sigmaChecks++;
        if (lowerByRule(s) !== s.toLowerCase()) fail('Final_Sigma rule disagrees with node on ' + JSON.stringify(s));
    };
    for (const xc of xs) {
        const X = String.fromCodePoint(xc);
        checkSigma(X + S); checkSigma(S + X);
        for (const Y of ys) {
            for (const t of [Y + S + X, X + S + Y, Y + X + S, S + X + Y, Y + S + X + Y]) checkSigma(t);
        }
        checkSigma(X + S + S);
    }
    for (let c = 0; c <= 0x10FFFF; c++) {
        if (isSurrogate(c) || !(cased(c) && ignorable(c))) continue;
        const X = String.fromCodePoint(c);
        checkSigma(X + S); checkSigma('Α' + S + X);
    }
    // 9. Context-freedom of whole-string mapping (Σ excepted for toLowerCase).
    for (let c = 0; c <= 0x10FFFF; c++) {
        if (isSurrogate(c)) continue;
        const X = String.fromCodePoint(c);
        const s = 'a' + X + 'b' + X;
        const U = X.toUpperCase();
        if (s.toUpperCase() !== 'A' + U + 'B' + U) fail('toUpperCase is context-sensitive at ' + hex(c));
        if (c !== 0x3A3) {
            const L = X.toLowerCase();
            if (s.toLowerCase() !== 'a' + L + 'b' + L) fail('toLowerCase is context-sensitive at ' + hex(c));
        }
    }
    process.stderr.write(`gen-casemap-tables: Unicode ${process.versions.unicode}: ${entries.length} entries, ` +
        `kUpper ${kUpper.length} (${kUpper.filter(([, v]) => v > 0x1FFFFF).length} encoded), ` +
        `kLower ${kLower.length} (${kLower.filter(([, v]) => v > 0x1FFFFF).length} encoded), ` +
        `kCased ${kCased.length}, kCaseIgnorable ${kCaseIgnorable.length}, ${sigmaChecks} Final_Sigma checks\n`);
    return emit({ kEntries, kUpper, kLower, kCased, kCaseIgnorable });
}

function emit(t) {
    const v = process.versions;
    const L = [];
    L.push('// GENERATED by `node compiler/scripts/gen-casemap-tables.mjs > runtime/src/allocator/CaseMapTables.hpp`');
    L.push(`// from node v${v.node} (Unicode ${v.unicode}, ICU ${v.icu}). Do not edit; see plans/char-case-mapping-elm-exact.md.`);
    L.push('#pragma once');
    L.push('#include <cstdint>');
    L.push('');
    L.push('namespace Elm::CaseMap {');
    L.push('');
    L.push(`inline constexpr const char* kUnicodeVersion = "${v.unicode}";  // process.versions.unicode`);
    L.push(`inline constexpr const char* kIcuVersion = "${v.icu}";  // informational`);
    L.push(`inline constexpr const char* kNodeVersion = "${v.node}";  // informational`);
    L.push(`inline constexpr uint32_t kEntryCount = ${t.kEntries.length};`);
    L.push(`inline constexpr uint32_t kMaxExpansionUnits = ${MAX_UNITS};`);
    L.push('');
    L.push('// One entry per distinct multi-code-point case-mapping string; index = rank; sorted by');
    L.push('// code-point sequence (a proper prefix first). upper/lower are Char values (ordinary or encoded).');
    L.push('struct Entry {');
    L.push('    uint16_t units[3];');
    L.push('    uint8_t len;');
    L.push('    uint8_t pad;');
    L.push('    uint32_t upper;');
    L.push('    uint32_t lower;');
    L.push('};');
    L.push(`inline constexpr Entry kEntries[${t.kEntries.length}] = {`);
    for (const e of t.kEntries) {
        const u = [...e.cps, 0, 0, 0].slice(0, 3).map((c) => hex(c));
        L.push(`    {{${u.join(', ')}}, ${e.cps.length}, 0, ${hex(e.upper, 8)}, ${hex(e.lower, 8)}},`);
    }
    L.push('};');
    L.push('');
    L.push('// Non-identity mappings for code points >= 0x80 (ASCII is the callers\' fast path), sorted by');
    L.push('// `from`; `to` is a Char value, encoded when the full mapping has more than one code point.');
    L.push('struct Pair {');
    L.push('    uint32_t from;');
    L.push('    uint32_t to;');
    L.push('};');
    for (const [name, rows] of [['kUpper', t.kUpper], ['kLower', t.kLower]]) {
        L.push(`inline constexpr uint32_t ${name}Count = ${rows.length};`);
        L.push(`inline constexpr Pair ${name}[${rows.length}] = {`);
        for (let i = 0; i < rows.length; i += 4) {
            L.push('    ' + rows.slice(i, i + 4).map(([a, b]) => `{${hex(a, 5)}, ${hex(b, 8)}}`).join(', ') + ',');
        }
        L.push('};');
    }
    L.push('');
    L.push('// Inclusive code-point ranges for String.toLower\'s Final_Sigma rule.');
    L.push('struct Range {');
    L.push('    uint32_t lo;');
    L.push('    uint32_t hi;');
    L.push('};');
    for (const [name, rows] of [['kCased', t.kCased], ['kCaseIgnorable', t.kCaseIgnorable]]) {
        L.push(`inline constexpr uint32_t ${name}Count = ${rows.length};`);
        L.push(`inline constexpr Range ${name}[${rows.length}] = {`);
        for (let i = 0; i < rows.length; i += 4) {
            L.push('    ' + rows.slice(i, i + 4).map(([a, b]) => `{${hex(a, 5)}, ${hex(b, 5)}}`).join(', ') + ',');
        }
        L.push('};');
    }
    L.push('');
    L.push('}  // namespace Elm::CaseMap');
    return L.join('\n') + '\n';
}

// The informational lines (node and ICU versions) may differ between equivalent runs.
const informational = (line) => line.startsWith('// from node v') || line.includes('kIcuVersion') || line.includes('kNodeVersion');

const args = process.argv.slice(2);
if (args.length === 0) {
    process.stdout.write(generate());
} else if (args[0] === '--check' && args.length === 2) {
    let existing;
    try { existing = fs.readFileSync(args[1], 'utf8'); } catch (e) { fail('cannot read ' + args[1]); }
    const m = /kUnicodeVersion = "([^"]+)"/.exec(existing);
    const fileVersion = m ? m[1] : '(none)';
    if (fileVersion !== process.versions.unicode) {
        fail(`node ${process.version} has Unicode ${process.versions.unicode}, tables are Unicode ${fileVersion}: ` +
            `use a node with Unicode ${fileVersion} or regenerate the tables (and re-record the conformance tests)`);
    }
    const strip = (s) => s.split('\n').filter((l) => !informational(l)).join('\n');
    if (strip(generate()) !== strip(existing)) {
        fail(args[1] + ' differs from what node ' + process.version + ' generates: regenerate it ' +
            '(and re-record the conformance tests)');
    }
    process.stderr.write('gen-casemap-tables: ' + args[1] + ' is up to date\n');
} else {
    fail('usage: gen-casemap-tables.mjs [--check <CaseMapTables.hpp>]');
}
