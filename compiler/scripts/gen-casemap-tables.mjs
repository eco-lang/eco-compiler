#!/usr/bin/env node
// Generates runtime/src/allocator/CaseMapTables.hpp, the Unicode simple case mapping behind
// Char.toUpper/toLower and String.toUpper/toLower (plans/char-simple-case-mapping.md,
// design_docs/char-case-mapping.md):
//
//     node compiler/scripts/gen-casemap-tables.mjs > runtime/src/allocator/CaseMapTables.hpp
//     node compiler/scripts/gen-casemap-tables.mjs --check runtime/src/allocator/CaseMapTables.hpp
//     node compiler/scripts/gen-casemap-tables.mjs --list-divergent
//
// The source is the vendored UnicodeData.txt (UCD below): field 12 is the simple uppercase
// mapping and field 13 the simple lowercase mapping, one code point to one code point. Every fact
// eco relies on is asserted on every run. When the running node has the same Unicode version, the
// tables are also cross-checked against node's toUpperCase/toLowerCase: wherever node's full mapping
// is one code point it must equal the simple mapping, so eco differs from Elm on JS only where full
// mapping gives several code points (--list-divergent prints those).
//
// `--check` exits 1 when node's Unicode version is not the tables' (the elm-conformance tests are
// recorded from node, so the two must match) or when the regenerated bytes differ.
import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

// The vendored data. To move to another Unicode version, see design_docs/char-case-mapping.md.
const UCD = {
    version: '17.0',
    dir: '17.0.0',
    sha256: '2e1efc1dcb59c575eedf5ccae60f95229f706ee6d031835247d843c11d96470c',
    upper: 1505,
    lower: 1488,
    // --list-divergent: code points whose full mapping has several code points, how many of them
    // the simple mapping leaves unchanged, and how many it maps up / down to one other code point.
    divergent: 103,
    divergentUnchanged: 75,
    divergentUp: 27,
    divergentLo: 1,
};

const here = path.dirname(fileURLToPath(import.meta.url));
const ucdPath = path.join(here, '..', '..', 'runtime', 'third_party', 'unicode', UCD.dir, 'UnicodeData.txt');
const ucdRel = `runtime/third_party/unicode/${UCD.dir}/UnicodeData.txt`;

function fail(msg) {
    process.stderr.write('gen-casemap-tables: ' + msg + '\n');
    process.exit(1);
}
function assert(cond, msg) { if (!cond) fail('assertion failed: ' + msg); }

const isSurrogate = (c) => c >= 0xD800 && c <= 0xDFFF;
const hex = (v) => '0x' + v.toString(16).toUpperCase().padStart(4, '0');
const hex4 = (v) => v.toString(16).toUpperCase().padStart(4, '0');

// Reads the vendored UnicodeData.txt and returns its non-identity simple mappings, sorted by code
// point, after asserting the facts the runtime and design_docs/char-case-mapping.md rely on.
function readTables() {
    let bytes;
    try { bytes = fs.readFileSync(ucdPath); } catch (e) { fail('cannot read ' + ucdPath); }
    const sha = crypto.createHash('sha256').update(bytes).digest('hex');
    assert(sha === UCD.sha256, `${ucdRel} has sha256 ${sha}, expected ${UCD.sha256}`);
    const upper = [], lower = [];
    for (const line of bytes.toString('utf8').split('\n')) {
        if (line === '') continue;
        const f = line.split(';');
        assert(f.length === 15, `malformed line: ${line}`);
        const cp = parseInt(f[0], 16);
        // A range line (<..., First> / <..., Last>) has empty fields 12 and 13, so it adds nothing.
        if (f[12] !== '') upper.push([cp, parseInt(f[12], 16)]);
        if (f[13] !== '') lower.push([cp, parseInt(f[13], 16)]);
    }
    for (const [name, rows] of [['upper', upper], ['lower', lower]]) {
        for (let i = 0; i < rows.length; i++) {
            const [a, b] = rows[i];
            assert(!isSurrogate(a) && !isSurrogate(b), `${name} ${hex(a)} -> ${hex(b)} involves a surrogate`);
            assert(a !== b, `${name} ${hex(a)} is an identity mapping`);
            assert(a <= 0x10FFFF && b <= 0x10FFFF, `${name} ${hex(a)} -> ${hex(b)} is out of range`);
            assert((a > 0xFFFF) === (b > 0xFFFF),
                `${name} ${hex(a)} -> ${hex(b)} crosses planes (would change a String's UTF-16 length)`);
            assert(i === 0 || rows[i - 1][0] < a, `${name} is not strictly increasing at ${hex(a)}`);
        }
    }
    assert(upper.length === UCD.upper, `${upper.length} upper mappings, expected ${UCD.upper}`);
    assert(lower.length === UCD.lower, `${lower.length} lower mappings, expected ${UCD.lower}`);
    return { upper, lower };
}

// Fails unless the running node has the tables' Unicode version.
function requireNodeVersion() {
    if (process.versions.unicode !== UCD.version) {
        fail(`node ${process.version} has Unicode ${process.versions.unicode}; the case tables are Unicode ` +
            `${UCD.version}. Use a node with Unicode ${UCD.version} (the elm-conformance tests are recorded ` +
            `from it), or update the vendored data and re-record (design_docs/char-case-mapping.md)`);
    }
}

// Wherever node's full mapping of a code point is one code point, it must be the simple mapping.
function crossCheckWithNode(t) {
    const up = new Map(t.upper), lo = new Map(t.lower);
    let checked = 0;
    for (let c = 0; c <= 0x10FFFF; c++) {
        if (isSurrogate(c)) continue;
        const s = String.fromCodePoint(c);
        const u = Array.from(s.toUpperCase(), (ch) => ch.codePointAt(0));
        const l = Array.from(s.toLowerCase(), (ch) => ch.codePointAt(0));
        if (u.length === 1) {
            assert(u[0] === (up.get(c) ?? c), `node uppercases ${hex(c)} to ${hex(u[0])}, simple mapping gives ${hex(up.get(c) ?? c)}`);
            checked++;
        }
        if (l.length === 1) {
            assert(l[0] === (lo.get(c) ?? c), `node lowercases ${hex(c)} to ${hex(l[0])}, simple mapping gives ${hex(lo.get(c) ?? c)}`);
            checked++;
        }
    }
    return checked;
}

function emit(t) {
    const L = [];
    L.push('// GENERATED by `node compiler/scripts/gen-casemap-tables.mjs > runtime/src/allocator/CaseMapTables.hpp`.');
    L.push('// Do not edit; see plans/char-simple-case-mapping.md and design_docs/char-case-mapping.md.');
    L.push(`// Source: ${ucdRel} (sha256 ${UCD.sha256}),`);
    L.push('// fields 12 (Simple_Uppercase_Mapping) and 13 (Simple_Lowercase_Mapping).');
    L.push('// Unicode data: Copyright © 1991-2026 Unicode, Inc. Unicode License v3 (runtime/third_party/unicode/LICENSE.TXT).');
    L.push('#pragma once');
    L.push('#include <cstdint>');
    L.push('');
    L.push('namespace Elm::CaseMap {');
    L.push('');
    L.push(`inline constexpr const char* kUnicodeVersion = "${UCD.version}";`);
    L.push('');
    L.push('// One non-identity simple mapping: `from` maps to `to`. Neither is a surrogate, and both are in');
    L.push('// the BMP or both above it.');
    L.push('struct CasePair {');
    L.push('    uint32_t from;');
    L.push('    uint32_t to;');
    L.push('};');
    for (const [name, rows] of [['kUpper', t.upper], ['kLower', t.lower]]) {
        L.push('');
        L.push(`// Every non-identity simple ${name === 'kUpper' ? 'uppercase' : 'lowercase'} mapping, ASCII included, sorted by \`from\`.`);
        L.push(`inline constexpr CasePair ${name}[${rows.length}] = {`);
        for (const [a, b] of rows) L.push(`    {${hex(a)}, ${hex(b)}},`);
        L.push('};');
    }
    L.push('');
    L.push('}  // namespace Elm::CaseMap');
    return L.join('\n') + '\n';
}

// Prints the code points where eco's simple mapping differs from Elm on JS (full mapping).
function listDivergent(t) {
    const up = new Map(t.upper), lo = new Map(t.lower);
    const lines = [];
    let unchanged = 0, upMapped = 0, loMapped = 0;
    for (let c = 0; c <= 0x10FFFF; c++) {
        if (isSurrogate(c)) continue;
        const s = String.fromCodePoint(c);
        for (const [dir, js, map] of [['up', s.toUpperCase(), up], ['lo', s.toLowerCase(), lo]]) {
            const full = Array.from(js, (ch) => ch.codePointAt(0));
            if (full.length < 2) continue;
            const simple = map.get(c);
            if (simple === undefined) unchanged++;
            else if (dir === 'up') upMapped++;
            else loMapped++;
            lines.push(`${hex4(c)} ${dir} simple ${simple === undefined ? '=' : hex4(simple)} elm ${full.map(hex4).join(' ')}`);
        }
    }
    assert(lines.length === UCD.divergent, `${lines.length} divergent code points, expected ${UCD.divergent}`);
    assert(unchanged === UCD.divergentUnchanged, `${unchanged} unchanged, expected ${UCD.divergentUnchanged}`);
    assert(upMapped === UCD.divergentUp, `${upMapped} mapped up, expected ${UCD.divergentUp}`);
    assert(loMapped === UCD.divergentLo, `${loMapped} mapped down, expected ${UCD.divergentLo}`);
    return lines.join('\n') + '\n';
}

const args = process.argv.slice(2);
if (args.length === 0) {
    requireNodeVersion();
    const t = readTables();
    const checked = crossCheckWithNode(t);
    process.stderr.write(`gen-casemap-tables: Unicode ${UCD.version}: kUpper ${t.upper.length}, ` +
        `kLower ${t.lower.length}, ${checked} single-code-point node mappings agree\n`);
    process.stdout.write(emit(t));
} else if (args[0] === '--list-divergent' && args.length === 1) {
    requireNodeVersion();
    process.stdout.write(listDivergent(readTables()));
} else if (args[0] === '--check' && args.length === 2) {
    let existing;
    try { existing = fs.readFileSync(args[1], 'utf8'); } catch (e) { fail('cannot read ' + args[1]); }
    requireNodeVersion();
    const t = readTables();
    crossCheckWithNode(t);
    if (emit(t) !== existing) {
        fail(args[1] + ' differs from what ' + ucdRel + ' generates: regenerate it ' +
            '(node compiler/scripts/gen-casemap-tables.mjs > ' + args[1] + ')');
    }
    process.stderr.write('gen-casemap-tables: ' + args[1] + ' is up to date\n');
} else {
    fail('usage: gen-casemap-tables.mjs [--check <CaseMapTables.hpp> | --list-divergent]');
}
