#!/usr/bin/env node
// Generates compiler/src/Compiler/GenerateJs/KernelOverride/Files.elm, the kernel overrides of
// compiler/kernel-overrides/*.js as Elm data for eco's JS backend (plans/js-kernel-overrides.md §3.1):
//
//     node compiler/scripts/gen-kernel-overrides.mjs > compiler/src/Compiler/GenerateJs/KernelOverride/Files.elm
//     node compiler/scripts/gen-kernel-overrides.mjs --check compiler/src/Compiler/GenerateJs/KernelOverride/Files.elm
//
// Only kernel overrides go into the module; value overrides are for Stage 1 (apply-overrides.js). Every
// `package` line must name the version that compiler/cmake/bootstrap/build-xhr/elm.json pins, so that a
// package bump forces a look at its overrides. `--check` exits 1 when the file differs from what would be
// written, or when the overrides do not parse.
import fs from "node:fs";
import path from "node:path";
import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";

const require = createRequire(import.meta.url);
const lib = require("./kernel-overrides-lib.js");
const here = path.dirname(fileURLToPath(import.meta.url));
const PINS = path.resolve(here, "../cmake/bootstrap/build-xhr/elm.json");

// `s` as an Elm string literal: printable ASCII as is, the usual escapes, and \u{...} for the rest.
function elmString(s) {
  let out = '"';
  for (const ch of s) {
    const c = ch.codePointAt(0);
    if (ch === "\\") out += "\\\\";
    else if (ch === '"') out += '\\"';
    else if (ch === "\n") out += "\\n";
    else if (ch === "\r") out += "\\r";
    else if (ch === "\t") out += "\\t";
    else if (c >= 0x20 && c <= 0x7e) out += ch;
    else out += "\\u{" + c.toString(16).toUpperCase().padStart(4, "0") + "}";
  }
  return out + '"';
}

function checkPins(overrides) {
  const deps = JSON.parse(fs.readFileSync(PINS, "utf8")).dependencies;
  const pinned = Object.assign({}, deps.indirect, deps.direct);
  for (const o of overrides) {
    for (const [name, version] of o.packages) {
      if (pinned[name] !== version) {
        throw new lib.OverrideError(
          `${o.file}: package ${name} ${version}, but ${path.relative(process.cwd(), PINS)} pins ${pinned[name] ?? "none"}; ` +
            "check the override against that version, then update its `package` line");
      }
    }
  }
}

function generate() {
  const all = lib.load();
  checkPins(all);
  const kernel = all.filter((o) => o.kind === "kernel");
  const entries = kernel.map((o) => {
    const requires = "[ " + o.requires.map(([p, h]) => `( ${elmString(p)}, ${elmString(h)} )`).join(", ") + " ]";
    return `{ file = ${elmString(o.file)}\n      , requires = ${requires}\n      , text = ${elmString(o.body)}\n      }`;
  });
  const list = entries.length === 0 ? "[]" : "[ " + entries.join("\n    , ") + "\n    ]";
  return `module Compiler.GenerateJs.KernelOverride.Files exposing (KernelOverride, all)

{-| GENERATED by compiler/scripts/gen-kernel-overrides.mjs from compiler/kernel-overrides/\\*.js; do not
edit. Change an override file and regenerate (plans/js-kernel-overrides.md).

The kernel overrides that eco's JavaScript back end emits between the kernel code and the Elm code
(\`Compiler.GenerateJs.KernelOverride\`).

@docs KernelOverride, all

-}


{-| One kernel override: its file name, the kernel modules it needs as ( prefix, home ) pairs such as
( "Elm", "Bytes" ), and its JavaScript text, emitted as written.
-}
type alias KernelOverride =
    { file : String
    , requires : List ( String, String )
    , text : String
    }


{-| Every kernel override, sorted by file name.
-}
all : List KernelOverride
all =
    ${list}
`;
}

const args = process.argv.slice(2);
try {
  const text = generate();
  if (args[0] === "--check") {
    if (!args[1]) throw new Error("--check needs the path of the generated module");
    const current = fs.existsSync(args[1]) ? fs.readFileSync(args[1], "utf8") : "";
    if (current !== text) {
      console.error(`gen-kernel-overrides: ${args[1]} is out of date; regenerate it:\n` +
        `  node compiler/scripts/gen-kernel-overrides.mjs > ${args[1]}`);
      process.exit(1);
    }
    console.log(`gen-kernel-overrides: OK (${args[1]})`);
  } else if (args.length === 0) {
    process.stdout.write(text);
  } else {
    throw new Error("usage: gen-kernel-overrides.mjs [--check <Files.elm>]");
  }
} catch (e) {
  console.error("gen-kernel-overrides: " + e.message);
  process.exit(1);
}
