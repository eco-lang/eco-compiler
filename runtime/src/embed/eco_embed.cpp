//===- eco_embed.cpp - C embedding API implementation ----------------------===//
//
// Implements eco_app_start/stop/join for hosts that link an Eco-compiled
// Elm program as a library (.so / .o). The eco-thread initialization
// mirrors eco_entry.cpp's standalone main() minus the signal handlers and
// GC-stats atexit printer (the host owns process-level concerns), plus:
//
//   - .llvm_stackmaps discovery works for BOTH executables and shared
//     objects: instead of assuming the main program, we locate the loaded
//     module that CONTAINS eco_main (the compiled Elm code) and parse its
//     stackmaps section.
//   - The scheduler holds one pendingAsync ref for the app lifetime so a
//     port-driven program does not exit when momentarily idle; the ref is
//     released by eco_app_stop.
//   - A ready handshake (PlatformRuntime::setReadyHook) makes
//     eco_app_start block until Platform.worker has dispatched its init
//     effects (or the program's main returned, for non-worker programs).
//
//===----------------------------------------------------------------------===//

