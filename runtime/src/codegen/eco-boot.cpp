// Win64 teardown hard-exit. eco-boot-native links all of LLVM/MLIR; returning
// from main runs the /MT CRT exit() -> ExitProcess, whose DLL_PROCESS_DETACH +
// static-destructor sweep intermittently stalls at process teardown. The
// lowering, the linked output binary and the stats are all complete by this
// point, so exit immediately as POSIX effectively does. TerminateProcess
// (unlike ExitProcess) skips DLL detach entirely, so it cannot wedge on a
// teardown lock. No-op on POSIX — the caller's `return` runs normally.
static void ecoBootFinalExit(int rc) {
#if defined(_WIN32)
    llvm::outs().flush();
    llvm::errs().flush();
    ::TerminateProcess(::GetCurrentProcess(), static_cast<UINT>(rc));
    // TerminateProcess is asynchronous; if it ever returns, do NOT fall through
    // to the CRT teardown — spin until the OS process rundown reaps us.
    for (;;) { ::Sleep(1000); }
#else
    // POSIX (plans/backend-lowering-optimization.md X1): every output is
    // written and the temp objects are removed by now, so skip teardown — the
    // multi-GB llvm::Module (its context, all GlobalValues, the value-name
    // tables) took ~1.5 s to free on the critical path. Keep a normal exit
    // when LLVM still has reports to print from its static destructors.
    if (!llvm::TimePassesIsEnabled && !llvm::AreStatisticsEnabled()) {
        llvm::outs().flush();
        llvm::errs().flush();
        std::fflush(nullptr);
        ::_exit(rc);
    }
#endif
}

int main(int argc, char **argv) {
#if defined(__GLIBC__)
    // Malloc tuning for the parallel phases (plans/backend-lowering-
    // optimization.md, malloc step): 41 % of the MLIR thread pool's samples
    // were kernel spinlocks — mmap_lock contention from glibc arenas growing
    // by mprotect and large blocks churning through mmap/munmap while every
    // other thread page-faults. Grow arenas in 64 MB steps, keep blocks up to
    // 32 MB inside the arenas, and never trim back. Process-local: the
    // shipped `eco` (which also hosts the Elm runtime) is not affected.
    mallopt(M_TOP_PAD, 64 << 20);
    mallopt(M_MMAP_THRESHOLD, 32 << 20);
    mallopt(M_TRIM_THRESHOLD, 1 << 30);
#endif
    llvm::InitLLVM initLLVM(argc, argv);

    // Initialize LLVM native target for object emission.
    llvm::InitializeNativeTarget();
    llvm::InitializeNativeTargetAsmPrinter();
    llvm::InitializeNativeTargetAsmParser();

    registerAsmPrinterCLOptions();
    registerMLIRContextCLOptions();
    registerPassManagerCLOptions();

    cl::ParseCommandLineOptions(argc, argv,
        "Eco native compiler\n\n"
        "Compiles Elm source files or MLIR to native x86-64 Linux executables.\n");

    std::string output = getOutputPath();

    // Lifetime spans the whole driver — phases below add to it via Scope, and
    // we print the aggregated table just before main() returns.
    eco::LoweringStats stats;

    // Fast path: when the input is an already-emitted object file, skip the
    // MLIR parse / lowering / LLVM-IR / RS4GC / object-emission pipeline and
    // go straight to the link step. This is the C++-only edit-test loop:
    // .mlir hasn't changed, only the runtime/kernel libraries have, so the
    // cached .o still reflects the current Elm-side compiler and only
    // re-linking is required.
    if (isObjectFile(inputFilename)) {
        if (emitAction != EmitExe) {
            llvm::errs()
                << "Error: when input is an object file, --emit must be 'exe' "
                << "(default); the MLIR/LLVM pipeline does not run for .o "
                << "input.\n";
            return 1;
        }
        int rc;
        {
            eco::LoweringStats::Scope scope(stats, "Link (clang++ driver)");
            rc = linkExecutable(inputFilename, output);
        }
        if (printStats) {
            stats.print(llvm::errs());
        }
        return rc;
    }

    // Step 1: Get MLIR input (either directly or via frontend compilation)
    std::string mlirFile;
    std::string tempMlirFile;

    if (isMlirFile(inputFilename)) {
        mlirFile = inputFilename;
    } else if (isElmFile(inputFilename)) {
        if (emitAction == EmitMLIR) {
            // Just run the frontend and output the MLIR
            std::string mlirOutput = (output == "-") ? "/dev/stdout" : output;
            int rc;
            {
                eco::LoweringStats::Scope scope(stats, "frontend (Elm -> MLIR)");
                rc = compileElmToMlir(inputFilename, mlirOutput);
            }
            if (printStats) {
                stats.print(llvm::errs());
            }
            return rc;
        }

        // Create a temp file for the MLIR intermediate
        llvm::SmallString<256> tempPath;
        if (auto ec = llvm::sys::fs::createTemporaryFile(
                "eco-boot", "mlir", tempPath)) {
            llvm::errs() << "Error: Could not create temp file: "
                         << ec.message() << "\n";
            return 1;
        }
        tempMlirFile = std::string(tempPath);
        mlirFile = tempMlirFile;

        {
            eco::LoweringStats::Scope scope(stats, "frontend (Elm -> MLIR)");
            if (compileElmToMlir(inputFilename, mlirFile) != 0) {
                llvm::sys::fs::remove(tempMlirFile);
                return 1;
            }
        }
    } else {
        llvm::errs()
            << "Error: Input file must be .elm, .mlir, or .o (re-link only)\n";
        return 1;
    }

    // Step 2: Parse MLIR.
    //
    // M6: the MLIRContext, the input MemoryBuffer (owned by `sourceMgr`) and
    // the ModuleOp are confined to the nested block opened here. Translation
    // produces an llvm::Module that depends only on `llvmContext`, and nothing
    // past translation reads MLIR state, so ending this scope immediately after
    // translateToLLVMIR frees the op graph, the context's uniquing storage and
    // the ~12MB source buffer before the memory-bandwidth-bound backend/worker
    // phase (lowers peak RSS). `llvmContext`/`llvmModule` are hoisted above the
    // block so they outlive it (and the backend); llvmContext must precede
    // llvmModule so the module is destroyed before its context at end of main.
    llvm::LLVMContext llvmContext;
    std::unique_ptr<llvm::Module> llvmModule;
    {
    DialectRegistry registry;
    eco::registerRequiredDialects(registry);

    MLIRContext context(registry);
#if defined(_WIN32)
    // Win64: run MLIR lowering single-threaded. MLIRContext's default ctor
    // spins up a per-context worker thread pool that parks for the context's
    // lifetime; the hard-exit (ecoBootFinalExit) already handles teardown, but
    // single-threading avoids leaving parked pool threads to be force-killed
    // and keeps lowering deterministic. The dominant cost (LLVM backend object
    // emission) is single-threaded regardless, so the wall-clock hit is small.
    context.disableMultithreading();
#endif
    eco::loadRequiredDialects(context);
    context.allowUnregisteredDialects();

    std::string errorMessage;
    auto inputFile = openInputFile(mlirFile, &errorMessage);
    if (!inputFile) {
        llvm::errs() << "Error: " << errorMessage << "\n";
        if (!tempMlirFile.empty())
            llvm::sys::fs::remove(tempMlirFile);
        return 1;
    }

    llvm::SourceMgr sourceMgr;
    sourceMgr.AddNewSourceBuffer(std::move(inputFile), llvm::SMLoc());

    OwningOpRef<ModuleOp> module;
    {
        eco::LoweringStats::Scope scope(stats, "MLIR parse + verify");
        module = loadMLIR(context, sourceMgr);
        if (!module) {
            if (!tempMlirFile.empty())
                llvm::sys::fs::remove(tempMlirFile);
            return 1;
        }

#ifdef ECO_LOWERING_VALIDATION
        // Redundant in release: parseSourceFile already verifies the parsed
        // module. Kept only in validation builds as a belt-and-braces check.
        if (failed(verify(*module))) {
            llvm::errs() << "Error: Module verification failed\n";
            if (!tempMlirFile.empty())
                llvm::sys::fs::remove(tempMlirFile);
            return 1;
        }
#endif
    }

    // Step 3: Run MLIR lowering pipeline (Eco -> LLVM dialect)
    {
        eco::LoweringStats::Scope scope(stats, "MLIR lowering pipeline");
        if (runPipeline(*module, stats, capPipelineOptions(output)) != 0) {
            if (!tempMlirFile.empty())
                llvm::sys::fs::remove(tempMlirFile);
            return 1;
        }
    }

    // Step 4: Translate to LLVM IR
    {
        eco::LoweringStats::Scope scope(stats, "MLIR -> LLVM IR translation");
        // plans/mlir-split-backend-00-spikes.md: diagnostic census of the
        // final llvm-dialect module (never modifies it).
        if (const char *spikeDir = ::getenv("ECO_SPIKE_DIR"))
            eco::runSpikeCensus(*module, spikeDir);
        llvmModule = translateToLLVMIR(*module, llvmContext);
        if (!llvmModule) {
            if (!tempMlirFile.empty())
                llvm::sys::fs::remove(tempMlirFile);
            return 1;
        }
    }
    } // end MLIR scope (M6): MLIRContext, sourceMgr (input buffer) and the
      // ModuleOp are destroyed here — the earliest point after translation.
      // Only llvmModule/llvmContext survive into TargetMachine init + backend.

    // Step 5: Create TargetMachine and set DataLayout BEFORE RS4GC (Phase 3
    // of the pipeline-convergence plan — matches the JIT path's ordering).
    // createEcoTargetMachine() is opt-level aware; that is load-bearing for
    // AOT -O0..-O3 codegen.
    std::unique_ptr<llvm::TargetMachine> tm;
    {
        eco::LoweringStats::Scope scope(stats, "TargetMachine init");
        tm = eco::createEcoTargetMachine(*llvmModule, optLevel.getValue());
        if (!tm)
            return 1;
    }

    // Clean up temp MLIR file now that we're done with it.
    if (!tempMlirFile.empty())
        llvm::sys::fs::remove(tempMlirFile);

    // EmitLLVM is a text-dump path: RS4GC via runEcoBackend(DumpLLVMText), then
    // tool-side opt + IR print. Object emission stays out of this branch.
    if (emitAction == EmitLLVM) {
        {
            eco::LoweringStats::Scope scope(stats, "LLVM RS4GC pipeline");
            eco::EcoBackendJob job;
            job.kind = eco::BackendKind::DumpLLVMText;
            job.tm = tm.get();
            job.needsFramePointerAttr = true;
            job.preRS4GCDumpPath = dumpPreRS4GCIR;
            job.postRS4GCDumpPath = dumpRS4GCIR;
            if (auto err = eco::runEcoBackend(*llvmModule, job)) {
                llvm::errs() << "Error: RS4GC failed: " << llvm::toString(std::move(err)) << "\n";
                return 1;
            }
        }
        if (optLevel > 0) {
            eco::LoweringStats::Scope scope(stats, "LLVM optimization (-O>0)");
            auto optPipeline = makeOptimizingTransformer(
                optLevel, /*sizeLevel=*/0, /*targetMachine=*/tm.get());
            if (auto err = optPipeline(llvmModule.get())) {
                llvm::errs() << "Error: LLVM optimization failed: " << llvm::toString(std::move(err)) << "\n";
                return 1;
            }
        }
        {
            eco::LoweringStats::Scope scope(stats, "Emit LLVM IR");
            if (output == "-") {
                llvm::outs() << *llvmModule << "\n";
            } else {
                std::error_code ec;
                llvm::raw_fd_ostream out(output, ec, llvm::sys::fs::OF_None);
                if (ec) {
                    llvm::errs() << "Error: Could not open output file: "
                                 << ec.message() << "\n";
                    return 1;
                }
                out << *llvmModule << "\n";
            }
        }
        if (printStats) {
            stats.print(llvm::errs());
        }
        return 0;
    }

    // EmitObj / EmitExe: target an object file path; runEcoBackend drives the
    // full RS4GC + opt + object-emit sequence. Exe linking stays in this tool
    // because it depends on EcoBootConfig.h's deployment paths.
    std::string objFile;
    std::string tempObjFile;
    // `-o foo.o` with the default --emit=exe is object-only output too.
    bool emitObjOnly =
        (emitAction == EmitObj) ||
        (output.size() >= 2 &&
         output.compare(output.size() - 2, 2, ".o") == 0);
    if (emitObjOnly) {
        objFile = output;
    } else {
        llvm::SmallString<256> tempPath;
        if (auto ec = llvm::sys::fs::createTemporaryFile(
                "eco-boot", "o", tempPath)) {
            llvm::errs() << "Error: Could not create temp file: "
                         << ec.message() << "\n";
            return 1;
        }
        tempObjFile = std::string(tempPath);
        objFile = tempObjFile;
    }

    const bool isExecutable = !emitObjOnly && !outputIsSharedLib(output);

    // Executable output only: internalize all generated symbols except the two
    // the C entry lib resolves by name, then GlobalDCE the unreachable
    // remainder — before RS4GC/opt/codegen. Skipped for object-only output
    // (relinked later, must keep symbols visible) and shared libs (need
    // __eco_root_module / napi exports).
    if (isExecutable) {
        eco::LoweringStats::Scope scope(stats, "Internalize + GlobalDCE");
        eco::internalizeAndDCEForExecutable(*llvmModule);
    } else if (emitObjOnly && !internalizeKeep.empty()) {
        // Opt-in for object output (--internalize-keep): the caller vouches
        // that the object's consumer references only these symbols.
        eco::LoweringStats::Scope scope(stats, "Internalize + GlobalDCE");
        llvm::SmallVector<llvm::StringRef> parts;
        llvm::StringRef(internalizeKeep).split(parts, ',', -1, false);
        std::vector<std::string> keep;
        for (llvm::StringRef k : parts)
            keep.push_back(k.trim().str());
        eco::internalizeAndDCE(*llvmModule, keep);
    }

    // Object output may also use the parallel split: the backend writes the
    // partitions to a temporary base path and a relocatable link (`ld -r`)
    // below combines them into the single requested object.
    std::string objPartsBase;
    if (emitObjOnly) {
        objPartsBase = objFile + ".part0.o";
    }

    // Parallel codegen: the partition policy now lives in the shared backend
    // (runEcoBackend / choosePartitionCount). We just declare eligibility +
    // the requested split level; runEcoBackend decides N, mints any extra temp
    // part files, and reports the produced set back via EcoBackendResult.
    eco::EcoBackendResult backendResult;
    {
        eco::LoweringStats::Scope scope(stats,
            "LLVM backend (RS4GC + opt + object emission)");
        eco::EcoBackendJob job;
        job.kind = eco::BackendKind::EmitObjectFile;
        job.tm = tm.get();
        job.optLevel = optLevel > 0
            ? static_cast<llvm::CodeGenOptLevel>(std::min(optLevel.getValue(), 3u))
            : llvm::CodeGenOptLevel::None;
        job.needsFramePointerAttr = true;
        job.preRS4GCDumpPath = dumpPreRS4GCIR;
        job.postRS4GCDumpPath = dumpRS4GCIR;
        job.rs4gcAfterOpt = rs4gcAfterOpt;
        job.splitCodegen = splitCodegen;
        job.splitEligible = isExecutable || emitObjOnly;
        job.capClosedWorld = capClosedWorld(output);
        job.parallelOpt = parallelOpt;
        job.stats = &stats;
        job.lazySplit = lazySplit;
        job.devEmitCodeGenLevel = devEmitCG;
        job.devOptO1 = devOptO1;
        job.objectFilePath = emitObjOnly ? objPartsBase : objFile;
        if (auto err = eco::runEcoBackend(*llvmModule, job, &backendResult)) {
            llvm::errs() << "Error: backend pipeline failed: " << llvm::toString(std::move(err)) << "\n";
            if (!tempObjFile.empty())
                llvm::sys::fs::remove(tempObjFile);
            for (auto &f : backendResult.ownedTempFiles)
                llvm::sys::fs::remove(f);
            return 1;
        }
    }

    if (verbose)
        llvm::errs() << "[eco-boot] emitted object file(s): "
                     << (backendResult.objectFiles.size() > 1
                             ? std::to_string(backendResult.objectFiles.size()) +
                                   " partitions"
                             : objFile)
                     << "\n";

    if (emitObjOnly) {
        int rc = 0;
        if (backendResult.objectFiles.size() == 1) {
            if (auto ec = llvm::sys::fs::rename(backendResult.objectFiles[0],
                                                objFile)) {
                llvm::errs() << "Error: could not move object to '" << objFile
                             << "': " << ec.message() << "\n";
                rc = 1;
            }
        } else {
            // Relocatable link of the partition objects into one object.
            // Each partition's .llvm_stackmaps section is concatenated, as in
            // the executable link (the runtime parses multiple blobs).
            eco::LoweringStats::Scope scope(stats, "Relocatable link (ld -r)");
            std::string linker = eco::config::systemLinker;
            llvm::SmallVector<llvm::StringRef> args = {linker, "-r", "-o",
                                                       objFile};
            for (const std::string &f : backendResult.objectFiles)
                args.push_back(f);
            std::string errMsg;
            rc = llvm::sys::ExecuteAndWait(linker, args, std::nullopt, {}, 0,
                                           0, &errMsg);
            if (rc != 0)
                llvm::errs() << "Error: relocatable link failed (rc=" << rc
                             << "): " << errMsg << "\n";
            for (const std::string &f : backendResult.objectFiles)
                llvm::sys::fs::remove(f);
        }
        for (auto &f : backendResult.ownedTempFiles)
            llvm::sys::fs::remove(f);
        if (printStats) {
            stats.print(llvm::errs());
        }
        ecoBootFinalExit(rc);
        return rc;
    }

    // Step 8: Link executable
    int rc;
    {
        eco::LoweringStats::Scope scope(stats, "Link (clang++ driver)");
        rc = linkExecutable(backendResult.objectFiles, output);
    }

    // Clean up temp object file(s)
    if (!tempObjFile.empty())
        llvm::sys::fs::remove(tempObjFile);
    for (auto &f : backendResult.ownedTempFiles)
        llvm::sys::fs::remove(f);

    if (printStats) {
        stats.print(llvm::errs());
    }
    eco::printOptPassTimes(llvm::errs());

    ecoBootFinalExit(rc);
    return rc;
}
