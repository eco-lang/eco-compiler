static OwningOpRef<ModuleOp> loadMLIR(MLIRContext &context,
                                       llvm::SourceMgr &sourceMgr) {
    auto module = parseSourceFile<ModuleOp>(sourceMgr, &context);
    if (!module)
        llvm::errs() << "Error: Failed to parse MLIR file\n";
    return module;
}

static int runPipeline(ModuleOp module, eco::LoweringStats &stats,
                       const eco::EcoPipelineOptions &pipeOpts) {
    PassManager pm(module->getName());

    if (failed(applyPassManagerCLOptions(pm)))
        return 1;

#ifndef ECO_LOWERING_VALIDATION
    // Release builds: skip the after-each-pass full-module verifier. The
    // parser already verified the input and the lowering passes are covered
    // by the test suite; a full verify after each of ~13 top-level passes is
    // O(module) each and pure overhead here. Validation builds keep it on to
    // localise any pass that emits invalid IR.
    pm.enableVerifier(false);
#endif

    // Per-pass timing — installed before passes are added so every pass
    // (including ones registered by buildEcoToLLVMPipeline) is observed.
    pm.addInstrumentation(stats.makePassInstrumentation());

    eco::buildEcoToLLVMPipeline(pm, pipeOpts);

    if (failed(pm.run(module)))
        return 1;

    return 0;
}

//===----------------------------------------------------------------------===//
// LLVM IR Translation
//===----------------------------------------------------------------------===//

static std::unique_ptr<llvm::Module> translateToLLVMIR(
    ModuleOp module, llvm::LLVMContext &llvmContext) {
    registerBuiltinDialectTranslation(*module->getContext());
    registerLLVMDialectTranslation(*module->getContext());

    // Release: skip the whole-module LLVM verifier on the translation output
    // (O(module) over ~85k functions; the MLIR pipeline already validated the
    // input). Validation builds keep it. Mirrors pm.enableVerifier(false).
#ifdef ECO_LOWERING_VALIDATION
    constexpr bool kDisableLLVMVerify = false;
#else
    constexpr bool kDisableLLVMVerify = true;
#endif
    auto llvmModule = translateModuleToLLVMIR(
        module, llvmContext, "LLVMDialectModule", kDisableLLVMVerify);
    if (!llvmModule) {
        llvm::errs() << "Error: Failed to translate MLIR to LLVM IR\n";
        return nullptr;
    }

    // Rename "main" to "eco_main" to avoid conflict with C main()
    // in the entry wrapper.
    if (auto *mainFn = llvmModule->getFunction("main")) {
        mainFn->setName("eco_main");
    }

    return llvmModule;
}

