#!/usr/bin/env python3
"""Generate src/Tensor/Axis.elm: the axis witnesses of the tensor API.

For ranks 1..5 and every position i (0-based):
  axis{i}of{n}  : Axis s r c       remove (or insert) the axis tagged c
  retag{i}of{n} : Retag s t a c    replace that axis's tag a by c
  last{n}, retagLast{n}            aliases for the last position
For input ranks 0..4: liftRank{n} : Lift z s t (prepend a batch axis z).
For ranks 2..5 and i < j: swap{i}{j}of{n} : Perm s t.
Every witness holds a non-negative axis index (MAX's softmax fails to compile on negative ones).

Usage: gen_axis.py > src/Tensor/Axis.elm
"""

TAGS = "abcde"


def shape(tags):
    return "R0" if not tags else "(R%d %s)" % (len(tags), " ".join(tags))


def main():
    names, defs = [], []

    def add(name, ty, body, doc=None):
        names.append(name)
        prefix = "{-| %s -}\n" % doc if doc else ""
        defs.append("%s%s : %s\n%s =\n    %s\n\n\n" % (prefix, name, ty, name, body))

    for n in range(1, 6):
        tags = list(TAGS[:n])
        for i in range(n):
            rest = tags[:i] + tags[i + 1:]
            add("axis%dof%d" % (i, n), "Axis %s %s %s" % (shape(tags), shape(rest), tags[i]), "I.Axis %d" % i)
            new = tags[:i] + ["z"] + tags[i + 1:]
            add("retag%dof%d" % (i, n), "Retag %s %s %s z" % (shape(tags), shape(new), tags[i]), "I.Retag %d" % i)
        add("last%d" % n, "Axis %s %s %s" % (shape(tags), shape(tags[:-1]), tags[-1]),
            "axis%dof%d" % (n - 1, n), "`axis%dof%d`." % (n - 1, n))
        add("retagLast%d" % n, "Retag %s %s %s z" % (shape(tags), shape(tags[:-1] + ["z"]), tags[-1]),
            "retag%dof%d" % (n - 1, n), "`retag%dof%d`." % (n - 1, n))
    for n in range(0, 5):
        tags = list(TAGS[:n])
        add("liftRank%d" % n, "Lift z %s %s" % (shape(tags), shape(["z"] + tags)), "I.Lift")
    for n in range(2, 6):
        tags = list(TAGS[:n])
        for i in range(n):
            for j in range(i + 1, n):
                t2 = tags[:]
                t2[i], t2[j] = t2[j], t2[i]
                add("swap%d%dof%d" % (i, j, n), "Perm %s %s" % (shape(tags), shape(t2)), "I.Perm [ ( %d, %d ) ]" % (i, j))

    groups = [", ".join(names[k:k + 8]) for k in range(0, len(names), 8)]
    print("module Tensor.Axis exposing\n    ( " + "\n    , ".join(groups) + "\n    , andThen\n    )\n")
    print("{-| Generated by scripts/gen_axis.py: which axis an operation acts on, typed by the shapes before")
    print("and after. Every witness holds a non-negative axis index.\n-}\n")
    print("import Tensor exposing (Axis, Lift, Perm, R0, R1, R2, R3, R4, R5, Retag)")
    print("import Tensor.Internal.Types as I\n\n")
    print("andThen : Perm t u -> Perm s t -> Perm s u\nandThen (I.Perm b) (I.Perm a) =\n    I.Perm (a ++ b)\n\n")
    print("".join(defs).rstrip())


if __name__ == "__main__":
    main()
