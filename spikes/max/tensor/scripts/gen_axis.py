#!/usr/bin/env python3
"""Generate src/Tensor/Axis.elm: the axis witnesses of the tensor API.

For ranks 1..5 and every position i (0-based):
  axis{i}of{n}  : Axis s r c       remove (or insert) the axis tagged c
  retag{i}of{n} : Retag s t a c    replace that axis's tag a by c
  last{n}, retagLast{n}            aliases for the last position
For input ranks 0..4: liftRank{n} : Lift z s t (prepend a batch axis z).
For ranks 2..5 and i < j: swap{i}{j}of{n} : Perm s t.
Every witness holds a non-negative axis index (MAX's softmax fails to compile on negative ones).

Usage: gen_axis.py | elm-format --stdin > src/Tensor/Axis.elm
"""

TAGS = "abcde"


def shape(tags):
    return "R0" if not tags else "(R%d %s)" % (len(tags), " ".join(tags))


def main():
    names, defs, sections = [], [], {}

    def add(name, ty, body, doc, section):
        names.append(name)
        sections.setdefault(section, []).append(name)
        prefix = "{-| %s -}\n" % doc if doc else ""
        defs.append("%s%s : %s\n%s =\n    %s\n\n\n" % (prefix, name, ty, name, body))

    for n in range(1, 6):
        tags = list(TAGS[:n])
        for i in range(n):
            rest = tags[:i] + tags[i + 1:]
            add("axis%dof%d" % (i, n), "Axis %s %s %s" % (shape(tags), shape(rest), tags[i]), "I.Axis %d" % i,
                "Axis %d of rank %d, counting from 0, which the operation removes or inserts." % (i, n),
                "Axes of rank %d" % n)
            new = tags[:i] + ["z"] + tags[i + 1:]
            add("retag%dof%d" % (i, n), "Retag %s %s %s z" % (shape(tags), shape(new), tags[i]), "I.Retag %d" % i,
                "Axis %d of rank %d, counting from 0, which the operation resizes and retags." % (i, n),
                "Axes of rank %d" % n)
        add("last%d" % n, "Axis %s %s %s" % (shape(tags), shape(tags[:-1]), tags[-1]),
            "axis%dof%d" % (n - 1, n), "`axis%dof%d`." % (n - 1, n), "Last axes")
        add("retagLast%d" % n, "Retag %s %s %s z" % (shape(tags), shape(tags[:-1] + ["z"]), tags[-1]),
            "retag%dof%d" % (n - 1, n), "`retag%dof%d`." % (n - 1, n), "Last axes")
    for n in range(0, 5):
        tags = list(TAGS[:n])
        add("liftRank%d" % n, "Lift z %s %s" % (shape(tags), shape(["z"] + tags)), "I.Lift",
            "A leading axis prepended to rank %d (`Tensor.stack`, `Transform.vmap`)." % n, "Leading axes")
    for n in range(2, 6):
        tags = list(TAGS[:n])
        for i in range(n):
            for j in range(i + 1, n):
                t2 = tags[:]
                t2[i], t2[j] = t2[j], t2[i]
                add("swap%d%dof%d" % (i, j, n), "Perm %s %s" % (shape(tags), shape(t2)), "I.Perm [ ( %d, %d ) ]" % (i, j),
                    "Swap axes %d and %d of rank %d." % (i, j, n), "Permutations")

    groups = [", ".join(names[k:k + 8]) for k in range(0, len(names), 8)]
    print("module Tensor.Axis exposing\n    ( " + "\n    , ".join(groups) + "\n    , andThen\n    )\n")
    sections.setdefault("Permutations", []).append("andThen")
    print("{-| Generated by scripts/gen_axis.py: which axis an operation acts on, typed by the shapes before")
    print("and after. Every witness holds a non-negative axis index.")
    order = ["Axes of rank %d" % n for n in range(1, 6)] + ["Last axes", "Leading axes", "Permutations"]
    for title in order:
        members = sections[title]
        print("\n\n# " + title + "\n")
        if title.startswith("Axes"):
            # one line for the axes, one for the retags
            lines = [[m for m in members if m.startswith(p)] for p in ("axis", "retag")]
        elif title == "Permutations":
            # one line per rank, andThen on its own
            lines = [[m for m in members if m.endswith("of%d" % n)] for n in range(2, 6)] + [["andThen"]]
        else:
            lines = [members]
        for line in lines:
            print("@docs " + ", ".join(line))
    print("\n-}\n")
    print("import Tensor exposing (Axis, Lift, Perm, R0, R1, R2, R3, R4, R5, Retag)")
    print("import Tensor.Internal.Types as I\n\n")
    print("{-| One permutation after another: `swap01of3 |> andThen swap12of3` swaps 0 and 1, then 1 and 2.\n-}")
    print("andThen : Perm t u -> Perm s t -> Perm s u\nandThen (I.Perm b) (I.Perm a) =\n    I.Perm (a ++ b)\n\n")
    print("".join(defs).rstrip())


if __name__ == "__main__":
    main()
