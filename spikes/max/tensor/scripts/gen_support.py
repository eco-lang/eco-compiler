#!/usr/bin/env python3
"""Generate src/Tensor/Internal/Support.elm from support.json (capi/scripts/inventory/support_probe.py):
the (primitive, dtype) pairs MAX refuses to compile on CPU, which the package then refuses when a
graph is built, with a clear message, instead of MAX's opaque compile failure.

Usage: gen_support.py support.json > src/Tensor/Internal/Support.elm
"""
import json
import sys

DT = {"f16": "F16", "bf16": "BF16", "f32": "F32", "f64": "F64", "si8": "SI8", "si32": "SI32",
      "si64": "SI64", "ui8": "UI8", "ui64": "UI64", "bool": "Bool"}


def main():
    table = json.load(open(sys.argv[1]))
    refused = sorted((prim, dt) for dt, prims in table.items() for prim, ok in prims.items() if not ok)
    print("module Tensor.Internal.Support exposing (refused)\n")
    print("{-| Generated by scripts/gen_support.py from the probe of MAX 26.7.0 on CPU")
    print("(capi/scripts/inventory/support_probe.py): the primitives, by their public names, that MAX")
    print("refuses to compile for a dtype. Everything else probed compiles.\n-}\n")
    print("import Tensor.Internal.Prim exposing (DT(..))\n\n")
    print("refused : String -> DT -> Bool")
    print("refused name dt =")
    if not refused:
        print("    False")
        return
    print("    case ( name, dt ) of")
    for prim, dt in refused:
        print(f'        ( "{prim}", {DT[dt]} ) ->\n            True\n')
    print("        _ ->\n            False")


if __name__ == "__main__":
    main()
