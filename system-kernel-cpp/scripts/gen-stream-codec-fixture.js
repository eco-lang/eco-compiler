#!/usr/bin/env node
// gen-stream-codec-fixture.js — compressed fixtures for the Stream codec tests
// (plans/eco-system-library.md Phase 6 step 6.3: "gzip round trip of 1 MiB, compared with a known
// gzip of the same data written by a test fixture").
//
// The oracle is node's zlib. The data is 1 MiB (1048576 bytes) of ASCII text: the lines
// "line <i mod 2000>\n" for i = 0, 1, 2, ..., concatenated and cut at 1048576 bytes. The Elm test
// (test/eco-system/src/StreamCodecGzipTest.elm) rebuilds the same text and checks that eco's
// gzipDecompression / deflateDecompression / deflateRawDecompression turn node's output back into
// it. Compressed bytes are not compared: node bundles its own zlib fork, which emits a different
// (equally valid) deflate stream than the system zlib eco links.
//
// The data repeats every 2000 lines (< 32 KiB), so each fixture is ~29 KB and is embedded as base64.
//
// Usage: node scripts/gen-stream-codec-fixture.js [outFile]
//        (default: ../test/eco-system/src/StreamCodecFixture.elm)
"use strict";
const fs = require("fs");
const path = require("path");
const zlib = require("zlib");

const SIZE = 1048576;

function data() {
    const parts = [];
    let len = 0;
    for (let i = 0; len < SIZE; i++) {
        const line = "line " + (i % 2000) + "\n";
        parts.push(line);
        len += line.length;
    }
    return Buffer.from(parts.join("").slice(0, SIZE), "latin1");
}

function wrap(name, doc, b64) {
    const width = 100;
    const chunks = [];
    for (let i = 0; i < b64.length; i += width) chunks.push(b64.slice(i, i + width));
    return [
        "",
        "",
        "{-| " + doc + " -}",
        name + " : String",
        name + " =",
        "    String.concat",
        "        [ " + chunks.map((c) => JSON.stringify(c)).join("\n        , "),
        "        ]",
    ].join("\n");
}

const d = data();
const gzip = zlib.gzipSync(d);
const deflate = zlib.deflateSync(d);
const raw = zlib.deflateRawSync(d);

const out = [
    "module StreamCodecFixture exposing (dataSize, deflateBase64, deflateRawBase64, gzipBase64)",
    "",
    "{-| GENERATED by system-kernel-cpp/scripts/gen-stream-codec-fixture.js (node " + process.version + " zlib " +
        process.versions.zlib + ") — do not edit.",
    "",
    "node's zlib output for the 1 MiB text `line <i mod 2000>\\n` (i = 0, 1, ...), cut at `dataSize` bytes.",
    "Not a test (no `main`).",
    "",
    "-}",
    "",
    "",
    "{-| Size of the uncompressed data. -}",
    "dataSize : Int",
    "dataSize =",
    "    " + SIZE,
    wrap("gzipBase64", "`zlib.gzipSync` (" + gzip.length + " bytes).", gzip.toString("base64")),
    wrap("deflateBase64", "`zlib.deflateSync` (" + deflate.length + " bytes).", deflate.toString("base64")),
    wrap("deflateRawBase64", "`zlib.deflateRawSync` (" + raw.length + " bytes).", raw.toString("base64")),
    "",
].join("\n");

const outFile = process.argv[2] ||
    path.join(__dirname, "..", "..", "test", "eco-system", "src", "StreamCodecFixture.elm");
fs.writeFileSync(outFile, out);
console.log("wrote " + outFile + " (gzip " + gzip.length + ", deflate " + deflate.length + ", raw " +
    raw.length + " bytes)");
